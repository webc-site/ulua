//! `Arc<T>`（cpp `std::shared_ptr<T>`）的可变句柄物化点——review.md §2
//! 「把 `unsafe` 关进一个有契约的最小边界，不得让 `unsafe` 和裸指针渗透到业务逻辑」
//! 在本 crate 的唯一落点。
//!
//! cpp 侧 `shared_ptr<Scope>`/`shared_ptr<Module>` 在单线程分析流程中随处直接写成员；
//! Rust 的 `Arc` 借不出 `&mut`（同一对象另有多份强引用），故既有写法是
//! `Arc::as_ptr(..) as *mut T` 再解引用，于是每个写入点都拖一个 `unsafe` 块。
//! 本模块把「派生裸指针 + 解引用」折叠为一次具名调用，业务侧只留普通字段访问。
//!
//! # 契约（所有调用点共同前提）
//!
//! 1. 入参 `Arc` 在返回引用的整个使用期内存活（同一语句内的临时 `Arc` 亦满足）；
//! 2. 分析/约束求解全程单线程驱动，同一对象任一时刻只有一条经本函数物化的可变
//!    借用存活，且与之并存的其它持有者当时不被读取；
//! 3. 只读路径不经本函数：`Arc` 的 `Deref` 已给出 `&T`。
//!
//! [`crate::functions::scope_slots`] 是 `Scope` 侧的具名写手门面，构建在本原语之上。

use alloc::sync::Arc;

/// 经 `Arc` 共享身份物化可变句柄（cpp `shared_ptr<T>` 直接写成员的直译）。
///
/// 返回 `'static` 以匹配迁移前裸指针写法的借用检查行为：刻意不受入参生命周期
/// 约束，避免收口改写反过来改变调用点的借用语义。
///
/// # Safety 前提
/// 见模块级契约三条：入参 `Arc` 存活覆盖返回值使用期、单线程驱动、
/// 同一对象无并存的可变别名与并发读取。
#[inline]
pub(crate) fn shared_mut<T>(arc: &Arc<T>) -> &'static mut T {
  // Safety: 契约由本函数全部调用点统一兑现（分析全程单线程驱动）；`Arc::as_ptr`
  // 给出分配基址，对象由入参 `Arc` 保活。
  unsafe { &mut *(Arc::as_ptr(arc).cast_mut()) }
}
